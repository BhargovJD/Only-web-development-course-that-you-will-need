// Datatypes in JavaScript

/*
String: A sequence of characters enclosed in single or double quotes.
Number: Represents numeric values, including integers and floating-point numbers.
Boolean: Represents a logical value, either true or false.
Undefined: A variable that has been declared but has not been assigned a value.
BigInt: Represents integers with arbitrary precision, allowing for very large numbers.
Undefined: A variable that has been declared but has not been assigned a value.
Null: Represents the intentional absence of any object value.
Object: A collection of key-value pairs, where each key is a string and the value can be any data type.
Symbol: A unique and immutable primitive value that can be used as a key for object properties.
*/

var score = 100; // Number
var name = "John"; // String
var isActive = true; // Boolean
var age = 25; // Number
var email = "john@example.com"; // String
var isStudent = false; // Boolean
var grade = 85.5; // Number
var hobbies = ["reading", "swimming"]; // Object (Array)
var address = { street: "123 Main St", city: "Anytown" }; // Object
var id = Symbol("id"); // Symbol

